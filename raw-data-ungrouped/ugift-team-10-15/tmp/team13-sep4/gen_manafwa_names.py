def block(name, day, rows):
    out = ["%s = {" % name]
    for wa, nn, desc, why in rows:
        src = "IMG-%s-WA%04d.jpg" % (day, wa)
        new = "%s_%s_ref%s-%04d.jpg" % (nn, desc, day, wa)
        out.append("    %r: (" % src)
        out.append("        %r," % new)
        out.append("        %r," % why)
        out.append("    ),")
    out.append("}")
    out.append("")
    return out


